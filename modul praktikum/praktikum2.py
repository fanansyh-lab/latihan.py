print("--- LATIHAN 1: VARIABEL DAN TIPE DATA ---")
nama_mahasiswa = "agus" # string
umur_mahasiswa = 24     # integer
tinggi_badan = 175.8    # float
status_aktif = True     # boolean

# menampilkan nilai variabel dan mngecek tipe datanya menggunakan type()
print("nama:", nama_mahasiswa, "| Tipe:", type(nama_mahasiswa))
print("umur:", umur_mahasiswa, "| Tipe:", type(umur_mahasiswa))
print("tinggi badan:", tinggi_badan, "| Tipe:", type(tinggi_badan))
print("status aktif:", status_aktif, "| Tipe:", type(status_aktif))

print("\n")#memberikan jarak spasi antar latihan

